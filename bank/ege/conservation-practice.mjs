function exercises(lesson, topic, rows) {
  return rows.map(([slug, prompt, answer, unit, solution, level]) => ({
    id: 'mechanics-' + slug,
    lesson,
    topic,
    type: 'number',
    prompt,
    answer: String(answer),
    unit,
    solution,
    level,
  }));
}

